namespace ShadUI;

/// <summary>
/// Specifies the edge of the parent container where the drawer should appear.
/// </summary>
public enum DrawerPlacement
{
    /// <summary>
    /// The drawer appears on the left edge.
    /// </summary>
    Left,

    /// <summary>
    /// The drawer appears on the right edge.
    /// </summary>
    Right,

    /// <summary>
    /// The drawer appears on the top edge.
    /// </summary>
    Top,

    /// <summary>
    /// The drawer appears on the bottom edge.
    /// </summary>
    Bottom
}
